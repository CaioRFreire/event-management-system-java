    private void jbPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPesquisarActionPerformed
        // EventoModel para pesquisar por id
        EventoModel evento = new EventoModel();
        // Comandos condicionais para verificar se campo está vazio ou não
        if(jtxIdEvento.getText().isEmpty()){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Preencha o código do evento!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            evento.setCodevento(Integer.parseInt(jtxIdEvento.getText()));
            // Controller
            EventoController controller = new EventoController();
            evento = controller.selecionar(evento);
            // Comando condicional para validar se objeto evento foi encontrado
            if(evento == null) {
                // Tela alertando que evento não foi encontrado
                JOptionPane.showMessageDialog(this, "Evento não encontrado!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else {
                // Preencher os campos
                jtxCategoria.setText(evento.getCategoria());
                jcbPlano.setSelectedItem(evento.getPlano());
                jtxValorPlano.setText(String.valueOf(evento.getValor_plano()));
                jcbCodAtividade.setSelectedItem(evento.getAtividade().getDescricao());
                jcbCodLocal.setSelectedItem(evento.getLocal().getNome());
                jcbCodParticipante.setSelectedItem(evento.getOrganizador());
                jcbCodProgramacao.setSelectedItem(evento.getProgramacao());
                jbNovo.setEnabled(false);
                jbSalvar.setEnabled(false);
                jbEditar.setEnabled(true);
                jbExcluir.setEnabled(true);
                jtxIdEvento.setEditable(false);
                jtxCategoria.setEditable(true);
                jcbPlano.setEditable(true);
                jtxValorPlano.setEditable(true);
                jcbCodAtividade.setEditable(true);
                jcbCodLocal.setEditable(true);
                jcbCodParticipante.setEditable(true);
                jcbCodProgramacao.setEditable(true);
            }
        }
    }//GEN-LAST:event_jbPesquisarActionPerformed
    
    // Método para preencher JtEvento
    private void preencherTabela(){
        EventoController controller = new EventoController();
        ArrayList<EventoModel> lista = controller.selecionarTodos();
        DefaultTableModel modeloTabela = (DefaultTableModel) jtEvento.getModel();
        modeloTabela.setRowCount(0);
        // Comando condicional para verificar se foi cadastrado
        if (lista.isEmpty()){
            // Tela alertando que nenhum evento foi cadastrado
            JOptionPane.showMessageDialog(this, "Nenhum evento cadastrado!" ,"Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            for(EventoModel e: lista) {
                modeloTabela.addRow(new String[]{
                    String.valueOf(e.getCodevento()),
                    e.getCategoria(),
                    e.getPlano(),
                    String.valueOf(e.getValor_plano()),
                    e.getAtividade().getDescricao(),
                    e.getLocal().getNome(),
                    e.getOrganizador().getNome(),
                    e.getProgramacao().getData_evento()
                });
            }
        }
    }
    
