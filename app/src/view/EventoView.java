    // Trava eventos do mouse quando clicado em algum objeto do JtEvento
    private void jtEventoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtEventoMouseClicked
        linha = jtEvento.getSelectedRow();
        if(linha !=-1){
            jtxIdEvento.setText(jtEvento.getValueAt(linha, 0).toString());
            jtxCategoria.setText(jtEvento.getValueAt(linha, 1).toString());
            jtxValorPlano.setText(jtEvento.getValueAt(linha, 4).toString());
            // JComboxbox de Atividade
            String ativ = jtEvento.getValueAt(linha, 3).toString();
            jcbCodAtividade.setSelectedItem(ativ);
            // JComboxbox de Local
            String loca = jtEvento.getValueAt(linha, 4).toString();
            jcbCodLocal.setSelectedItem(loca);
            // JComboxbox de Participante
            String part = jtEvento.getValueAt(linha, 5).toString();
            jcbCodParticipante.setSelectedItem(part);
            // JComboxbox de Programação
            String prog = jtEvento.getValueAt(linha, 6).toString();
            jcbCodProgramacao.setSelectedItem(prog);
            // JComboBox de Plano
            jbNovo.setEnabled(false);
            jbSalvar.setEnabled(false);
            jbEditar.setEnabled(true);
            jbExcluir.setEnabled(true);
            jtxIdEvento.setEditable(false);
            jtxCategoria.setEditable(true);
            jtxValorPlano.setEditable(true);  
            jcbPlano.setEditable(true);
            linha = -1;
        }
    }//GEN-LAST:event_jtEventoMouseClicked

