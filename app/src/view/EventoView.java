    // Ações válidas quando pressionado o botão jbSalvar
    private void jbSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalvarActionPerformed
        // Comandos condicionais para verificar se campo está vazio ou não
        if((jtxCategoria.getText().isEmpty()) || (jtxValorPlano.getText()).isEmpty() || (jcbPlano.getSelectedItem() == null)) {
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Digite todos os campos!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else{
            // Inteiros, Strings e Objetos locais para coletar e armazenar dos JTextField e JComboBox
            // Strings
            String categoria = jtxCategoria.getText();
            String ativ = (String) jcbCodAtividade.getSelectedItem();
            String loca = (String) jcbCodLocal.getSelectedItem();
            String part = (String) jcbCodParticipante.getSelectedItem();
            String prog = (String) jcbCodProgramacao.getSelectedItem();
            // Objeto
            Object plano = (Object) jcbPlano.getSelectedItem();
            // Inteiros
            int valor_plano = Integer.parseInt(jtxValorPlano.getText());
            // Comandos de repetição para coletar a lista
            int atividade = 0;
            for(int i=0; i<listaAtividades.size();i++){
                if(ativ.equals(listaAtividades.get(i).getDescricao())){
                    atividade = listaAtividades.get(i).getIdatividade();
                    break;
                }
            }
            // Local
            int local = 0;
            for(int i=0; i<listaLocais.size();i++){
                if(loca.equals(listaLocais.get(i).getNome())){
                    local = listaLocais.get(i).getIdlocal();
                    break;
                }
            }
            // Participante
            int organizador = 0;
            for(int i=0; i<listaOrganizadores.size();i++){
                if(part.equals(listaOrganizadores.get(i).getNome())){
                    organizador = listaOrganizadores.get(i).getIdorganizador();
                    break;
                }
            }
            // Programação
            int programacao = 0;
            for(int i=0; i<listaProgramacoes.size();i++){
                if(prog.equals(listaProgramacoes.get(i).getData_evento())){
                    programacao = listaProgramacoes.get(i).getIdprogramacao();
                    break;
                }
            }
            EventoModel evento = new EventoModel();
            evento.setCategoria(categoria);
            evento.setValor_plano(valor_plano);
            evento.setPlano(plano.toString());
            // Chaves Estrangeiras
            evento.getAtividade().setIdatividade(atividade);
            evento.getLocal().setIdlocal(local);
            evento.getOrganizador().setIdorganizador(organizador);
            evento.getProgramacao().setIdprogramacao(programacao);
            //CONTROLLER
            EventoController controller = new EventoController();
            // Comandos condicionais para validar se controller funcionou ou não
            if(controller.inserir(evento)){
                JOptionPane.showMessageDialog(this, "Evento inserido com sucesso!", "Sucesso" ,JOptionPane.INFORMATION_MESSAGE);
                // Chamar métodos
                limparCampos();
                inicializa();
                preencherTabela();
            }else
                JOptionPane.showMessageDialog(this, "Erro ao inserir o evento!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jbSalvarActionPerformed

