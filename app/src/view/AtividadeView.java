    // Ações válidas quando pressionado o botão jbSalvar
    private void jbSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalvarActionPerformed
        // Strings locais para coletar e armazenar dos JTextField
        String descricao = jtxDescricao.getText();
        String responsavel = jtxResponsavel.getText();
        String musico = jtxMusico.getText();
        String genero = jtxGenero.getText();
        String buffet = jtxBuffet.getText();
        String tipo_cardapio = jtxTipoCardapio.getText();
        String decoracao = jtxBuffet.getText();
        String danca = jtxDanca.getText();
        String midia = jtxMidia.getText();
        if ((jtxDescricao.getText().isEmpty()) || (jtxResponsavel.getText().isEmpty())){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Digite descricão e atividade!", "Erro ao salvar atividade", JOptionPane.ERROR_MESSAGE);
        }
        else {
            // Atribuir valores ao AtividadeModel
            AtividadeModel atividade = new AtividadeModel();
            atividade.setDescricao(descricao);
            atividade.setResponsavel(responsavel);
            atividade.setMusico(musico);
            atividade.setGenero(genero);
            atividade.setBuffet(buffet);
            atividade.setTipo_cardapio(tipo_cardapio);
            atividade.setDecoracao(decoracao);
            atividade.setDanca(danca);
            atividade.setMidia(midia);
            // Controller
            AtividadeController controller = new AtividadeController();
            // Comandos condicionais para validar se controller funcionou ou não
            if (controller.inserir(atividade)) {
                JOptionPane.showMessageDialog(this, "Atividade inserida com sucesso!", "Sucesso" ,JOptionPane.INFORMATION_MESSAGE);
                // Chamar métodos
                limparCampos();
                inicializa();
                preencherTabela();
            }
            else {
                // Tela alertando o usuário sobre o erro
                JOptionPane.showMessageDialog(this, "Erro ao inserir um atividade!", "Erro" ,JOptionPane.ERROR_MESSAGE);
            }
        }
        
        
    }//GEN-LAST:event_jbSalvarActionPerformed

