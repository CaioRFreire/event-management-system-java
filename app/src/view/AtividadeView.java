    private void jbPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPesquisarActionPerformed
        // AtividadeModel para pesquisar por id
        AtividadeModel atividade = new AtividadeModel();
        // Comandos condicionais para verificar se campo está vazio ou não
        if(jtxIdAtividade.getText().isEmpty()){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Preencha o código da atividade!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            atividade.setIdatividade(Integer.parseInt(jtxIdAtividade.getText()));
            // Controller
            AtividadeController controller = new AtividadeController();
            atividade = controller.selecionar(atividade);
            // Comando condicional para validar se objeto atividade foi encontrado
            if(atividade == null) {
                // Tela alertando que atividade não foi encontrado
                JOptionPane.showMessageDialog(this, "Atividade não encontrada!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else {
                // Preencher os campos
                jtxDescricao.setText(atividade.getDescricao());
                jtxResponsavel.setText(atividade.getResponsavel());
                jtxMusico.setText(atividade.getMusico());
                jtxGenero.setText(atividade.getGenero());
                jtxBuffet.setText(atividade.getBuffet());
                jtxTipoCardapio.setText(atividade.getTipo_cardapio());
                jtxBuffet.setText(atividade.getDecoracao());
                jtxDanca.setText(atividade.getDanca());
                jtxMidia.setText(atividade.getMidia());
                jbNovo.setEnabled(false);
                jbSalvar.setEnabled(false);
                jbEditar.setEnabled(true);
                jbExcluir.setEnabled(true);  
                jtxIdAtividade.setEditable(false);
                jtxDescricao.setEditable(true);
                jtxResponsavel.setEditable(true);
                jtxMusico.setEditable(true);
                jtxGenero.setEditable(true);
                jtxBuffet.setEditable(true);
                jtxTipoCardapio.setEditable(true);
                jtxBuffet.setEditable(true);
                jtxDanca.setEditable(true);
                jtxMidia.setEditable(true);
            }
        }
    }
        
    // Método para preencher JtAtividade
    private void preencherTabela(){
        AtividadeController controller = new AtividadeController();
        ArrayList<AtividadeModel> lista = controller.selecionarTodos();
        DefaultTableModel modeloTabela = (DefaultTableModel) jtAtividade.getModel();
        modeloTabela.setRowCount(0);
        // Comando condicional para verificar se foi cadastrado
        if (lista.isEmpty()){
            // Tela alertando que nenhuma atividade foi cadastrada
            JOptionPane.showMessageDialog(this, "Nenhuma atividade cadastrada!" ,"Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            for(AtividadeModel a: lista) {
                modeloTabela.addRow(new String[]{
                    String.valueOf(a.getIdatividade()),
                    a.getDescricao(),
                    a.getResponsavel(),
                    a.getMusico(),
                    a.getGenero(),
                    a.getBuffet(),
                    a.getTipo_cardapio(),
                    a.getDecoracao(),
                    a.getDanca(),
                    a.getMidia(),
                });
            }
        }
    }
    
