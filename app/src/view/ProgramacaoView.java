    // Ações quando pressionado o botão jbPesquisar
    private void jbPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPesquisarActionPerformed
        // ParticipanteModel para pesquisar por id
        ProgramacaoModel programacao = new ProgramacaoModel();
        // Comandos condicionais para verificar se campo está vazio ou não
        if(jtxIdProgramacao.getText().isEmpty()) {
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Preencha o código da programação!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else{
            programacao.setIdprogramacao(Integer.parseInt(jtxIdProgramacao.getText()));
            // Controller
            ProgramacaoController controller = new ProgramacaoController();
            programacao = controller.selecionar(programacao);
            // Comando condicional para validar se objeto programação foi encontrado
            if(programacao == null) {
                // Tela alertando que programação não foi encontrada
                JOptionPane.showMessageDialog(this, "Programação não encontrada!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else {
                // Preencher os campos
                jtxDataEvento.setText(programacao.getData_evento());
                jtxHoraInicio.setText(programacao.getHora_inicio());
                jtxHoraFim.setText(programacao.getHora_fim());
                jbNovo.setEnabled(false);
                jbSalvar.setEnabled(false);
                jbEditar.setEnabled(true);
                jbExcluir.setEnabled(true);
                jtxIdProgramacao.setEditable(false);
                jtxDataEvento.setEditable(true);
                jtxHoraInicio.setEditable(true);
                jtxHoraFim.setEditable(true);
            }
        }
    }//GEN-LAST:event_jbPesquisarActionPerformed
    
    // Método para preencher JtProgramacao
    private void preencherTabela(){
        ProgramacaoController controller = new ProgramacaoController();
        ArrayList<ProgramacaoModel> lista = controller.selecionarTodos();
        DefaultTableModel modeloTabela = (DefaultTableModel) jtProgramacao.getModel();
        modeloTabela.setRowCount(0);
        // Comando condicional para verificar se foi cadastrado
        if(lista.isEmpty()) {
            // Tela alertando que nenhuma programação foi cadastrada
            JOptionPane.showMessageDialog(this, "Nenhuma programação cadastrada!","Erro", JOptionPane.ERROR_MESSAGE);
        }
        else{
            for(ProgramacaoModel p: lista){
                modeloTabela.addRow(new String[]{
                    String.valueOf(p.getIdprogramacao()),
                    p.getData_evento(),
                    p.getHora_inicio(),
                    p.getHora_fim()
                });
            }
        }
    }
    
