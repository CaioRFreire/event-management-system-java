    // Ações válidas quando pressionado o botão jbSalvar
    private void jbSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalvarActionPerformed
        // Strings para coletar e armazenar JTextField
        String data_evento = jtxDataEvento.getText();
        String hora_inicio = jtxHoraInicio.getText();
        String hora_fim = jtxHoraFim.getText();
        // Comandos condicionais para verificar se campo está vazio ou não
        if((jtxDataEvento.getText().isEmpty())||(jtxHoraInicio.getText().isEmpty())||(jtxHoraFim.getText().isEmpty()))
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Digite todos os campos!", "Erro ao salvar programação", JOptionPane.ERROR_MESSAGE);
        else{
            // Atribuir valores ao ProgramacaoModel
            ProgramacaoModel programacao = new ProgramacaoModel();
            programacao.setData_evento(data_evento);
            programacao.setHora_inicio(hora_inicio);
            programacao.setHora_fim(hora_fim);
            // Controller
            ProgramacaoController controller = new ProgramacaoController();
            // Comandos condicionais para validar se controller funcionou ou não
            if(controller.inserir(programacao)){
                JOptionPane.showMessageDialog(this, "Programação inserida com sucesso!", "Sucesso" ,JOptionPane.INFORMATION_MESSAGE);
                // Chamar métodos
                limparCampos();
                inicializa();
                preencherTabela();
            }
            else {
                // Tela alertando o usuário sobre o erro
                JOptionPane.showMessageDialog(this, "Erro ao inserir uma programação!", "Retorno BD", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jbSalvarActionPerformed

