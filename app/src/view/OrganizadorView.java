    // Ações quando pressionado o botão jbPesquisar
    private void jbPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPesquisarActionPerformed
        // OrganizadorModel para pesquisar por id
        OrganizadorModel organizador = new OrganizadorModel();
        // Comandos condicionais para verificar se campo está vazio ou não
        if(jtxIdOrganizador.getText().isEmpty()){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Preencha o código do organizador!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            organizador.setIdorganizador(Integer.parseInt(jtxIdOrganizador.getText()));
            // Controller
            OrganizadorController controller = new OrganizadorController();
            organizador = controller.selecionar(organizador);
            // Comando condicional para validar se objeto organizador foi encontrado
            if(organizador == null) {
                // Tela alertando que organizador não foi encontrado
                JOptionPane.showMessageDialog(this, "Organizador não encontrado!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else {
                // Preencher os campos
                jtxCpf.setText(organizador.getCpf());
                jtxNome.setText(organizador.getNome());
                jtxDataNasc.setText(organizador.getData_nasc());
                jtxTelefone.setText(organizador.getTelefone());
                jbNovo.setEnabled(false);
                jbSalvar.setEnabled(false);
                jbEditar.setEnabled(true);
                jbExcluir.setEnabled(true);
                jtxIdOrganizador.setEditable(false);
                jtxNome.setEditable(true);
                jtxCpf.setEditable(true);
                jtxDataNasc.setEditable(true);
                jtxTelefone.setEditable(true);
            }
        }
    }//GEN-LAST:event_jbPesquisarActionPerformed

// Trava eventos do mouse quando clicado em algum objeto do JtOrganizador
