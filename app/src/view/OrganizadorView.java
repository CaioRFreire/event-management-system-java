    // Ações válidas quando pressionado o botão jbSalvar
    private void jbSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalvarActionPerformed
        // Strings locais para coletar e armazenar dos JTextField
        String cpf = jtxCpf.getText();
        String nome = jtxNome.getText();
        String data_nasc = jtxDataNasc.getText();
        String telefone = jtxTelefone.getText();
        // Comandos condicionais para verificar se campo está vazio ou não
        if ((jtxCpf.getText().isEmpty()) || (jtxNome.getText().isEmpty()) || jtxDataNasc.getText().isEmpty() || jtxTelefone.getText().isEmpty()){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Digite todos os campos!", "Erro ao salvar organizador", JOptionPane.ERROR_MESSAGE);
        }
        else {
            // Atribuir valores ao OrganizadorModel
            OrganizadorModel organizador = new OrganizadorModel();
            organizador.setCpf(cpf);
            organizador.setNome(nome);
            organizador.setData_nasc(data_nasc);
            organizador.setTelefone(telefone);               
            // Controller
            OrganizadorController controller = new OrganizadorController();
            // Comandos condicionais para validar se controller funcionou ou não
            if (controller.inserir(organizador)) {
                JOptionPane.showMessageDialog(this, "Organizador inserido com sucesso!", "Sucesso" ,JOptionPane.INFORMATION_MESSAGE);
                // Chamar métodos
                limparCampos();
                inicializa();
                preencherTabela();
            }
            else {
                // Tela alertando o usuário sobre o erro
                JOptionPane.showMessageDialog(this, "Erro ao inserir um organizador!", "Erro" ,JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jbSalvarActionPerformed

