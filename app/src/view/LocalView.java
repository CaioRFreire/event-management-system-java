    // Ações quando pressionado o botão jbPesquisar
    private void jbPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPesquisarActionPerformed
        // LocalModel para pesquisar por id
        LocalModel local = new LocalModel();
        // Comandos condicionais para verificar se campo está vazio ou não
        if(jtxIdLocal.getText().isEmpty()){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Preencha o código do local!", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            local.setIdlocal(Integer.parseInt(jtxIdLocal.getText()));
            // Controller
            LocalController controller = new LocalController();
            local = controller.selecionar(local);
            // Comando condicional para validar se objeto local foi encontrado
            if(local == null) {
                // Tela alertando que local não foi encontrado
                JOptionPane.showMessageDialog(this, "Local não encontrado!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
            else {
                // Preencher os campos
                jtxNome.setText(local.getNome());
                jtxEndereco.setText(local.getEndereco());
                jtxCapacidade.setText(String.valueOf(local.getCapacidade()));
                jtxQuantidadeParticipantes.setText(String.valueOf(local.getQuantidade_participantes()));
                jbNovo.setEnabled(false);
                jbSalvar.setEnabled(false);
                jbEditar.setEnabled(true);
                jbExcluir.setEnabled(true);
                jtxIdLocal.setEditable(false);
                jtxEndereco.setEditable(true);
                jtxNome.setEditable(true);
                jtxCapacidade.setEditable(true);
                jtxQuantidadeParticipantes.setEditable(true);
                jlstRecursosDisponiveis.setEnabled(true);
                jlstAcessibilidade.setEnabled(true);
            }
        }
    }//GEN-LAST:event_jbPesquisarActionPerformed

    // Método para preencher JtLocal
    private void preencherTabela(){
        LocalController controller = new LocalController();
        ArrayList<LocalModel> lista = controller.selecionarTodos();
        DefaultTableModel modeloTabela = (DefaultTableModel) jtLocal.getModel();
        modeloTabela.setRowCount(0);
        // Comando condicional para verificar se foi cadastrado
        if (lista.isEmpty()){
            // Tela alertando que nenhum local foi cadastrado
            JOptionPane.showMessageDialog(this, "Nenhum local cadastrado!" ,"Erro", JOptionPane.ERROR_MESSAGE);
        }
        else {
            for(LocalModel l: lista) {
                modeloTabela.addRow(new String[]{
                    String.valueOf(l.getIdlocal()),
                    l.getNome(),
                    l.getEndereco(),
                    String.valueOf(l.getCapacidade()),
                    l.getRecursos_disponiveis(),
                    l.getAcessibilidade(),
                    String.valueOf(l.getQuantidade_participantes())
                });
            }
        }
    }
    
