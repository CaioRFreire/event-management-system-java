    // Ações válidas quando pressionado o botão jbSalvar
    private void jbSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalvarActionPerformed
        // Inteiros, Strings e Listas locais para coletar e armazenar dos JTextField e JComboBox
        String nome = jtxNome.getText();
        String endereco = jtxEndereco.getText();
        int quantidade_participantes = Integer.parseInt(jtxQuantidadeParticipantes.getText());
        int capacidade = Integer.parseInt(jtxCapacidade.getText());
        List <String> recursos_selecionados = jlstRecursosDisponiveis.getSelectedValuesList();
        List <String> acessibilidades_selecionadas = jlstAcessibilidade.getSelectedValuesList();
        // Comandos condicionais para verificar se campo está vazio ou não
        if ((jtxNome.getText().isEmpty()) || (jtxEndereco.getText().isEmpty()) || (jtxCapacidade.getText().isEmpty()) || (recursos_selecionados.isEmpty()) || (acessibilidades_selecionadas.isEmpty()) || (jtxQuantidadeParticipantes.getText().isEmpty())){
            // Tela alertando o usuário sobre o erro
            JOptionPane.showMessageDialog(this, "Digite e selecione todos os campos!", "Erro ao salvar local", JOptionPane.ERROR_MESSAGE);
        }
        else {
            // Atribuir valores ao LocalModel
            LocalModel local = new LocalModel();
            // JTextField
            local.setNome(nome);
            local.setEndereco(endereco);
            local.setCapacidade(capacidade);
            local.setQuantidade_participantes(quantidade_participantes);
            // Jlist
            String recursos_texto = String.join(", ", recursos_selecionados);
            local.setRecursos_disponiveis(recursos_texto);          
            String acessibilidade_texto = String.join(", ", acessibilidades_selecionadas);
            local.setAcessibilidade(acessibilidade_texto);
            // Controller
            LocalController controller = new LocalController();
            // Comandos condicionais para validar se controller funcionou ou não
            if (controller.inserir(local)) {
                JOptionPane.showMessageDialog(this, "Local inserido com sucesso!", "Sucesso" ,JOptionPane.INFORMATION_MESSAGE);
                // Chamar métodos
                limparCampos();
                inicializa();
                preencherTabela();
            }
            else {
                // Tela alertando o usuário sobre o erro
                JOptionPane.showMessageDialog(this, "Erro ao inserir um local!", "Erro" ,JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jbSalvarActionPerformed

